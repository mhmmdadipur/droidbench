#!/usr/bin/env bash
# Removes build output so the project folder is small and tidy again.
#
#   bash scripts/clean.sh              build output only (safe, rebuilt by any build)
#   bash scripts/clean.sh --deps       ... plus node_modules
#   bash scripts/clean.sh --binaries   ... plus downloaded tools in src-tauri/binaries
#   bash scripts/clean.sh --all        everything above
#   bash scripts/clean.sh --dry-run    only list what would be removed (combine with any flag)
#
# After --deps / --binaries / --all, restore everything with one command: bash scripts/setup.sh
#
# Never touched: source code, src-tauri/binaries/*.apk (tracked in git), .gitkeep,
# git history, the updater key in ~/.droidbench-keys, and anything outside this folder.
set -euo pipefail
cd "$(dirname "$0")/.."

DEPS=0
BINS=0
DRY=0
for arg in "$@"; do
  case "$arg" in
    --deps) DEPS=1 ;;
    --binaries) BINS=1 ;;
    --all) DEPS=1; BINS=1 ;;
    --dry-run|-n) DRY=1 ;;
    -h|--help) sed -n '2,13p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "unknown option: $arg (see --help)" >&2; exit 1 ;;
  esac
done

size() { du -sh "$1" 2>/dev/null | cut -f1; }
TOTAL_FREED=0

remove() {
  local path="$1" note="${2:-}"
  [ -e "$path" ] || return 0
  local sz; sz="$(size "$path")"
  if [ "$DRY" = 1 ]; then
    echo "  would remove  $path  ($sz) $note"
  else
    rm -rf "$path"
    echo "  removed       $path  ($sz) $note"
  fi
}

echo "==> Build output"
# cargo clean knows its own layout; fall back to deleting the folder if cargo is missing
if [ -d src-tauri/target ] && [ "$DRY" = 0 ] && command -v cargo >/dev/null 2>&1; then
  cargo clean --manifest-path src-tauri/Cargo.toml 2>&1 | tail -1 || true
fi
remove src-tauri/target
remove src-tauri/gen "(regenerated by tauri-build)"
remove dist
remove dist-ssr
remove node_modules/.vite
remove tsconfig.tsbuildinfo
remove tsconfig.node.tsbuildinfo

if [ "$DEPS" = 1 ]; then
  echo "==> Dependencies"
  remove node_modules "(restore: bash scripts/setup.sh)"
fi

if [ "$BINS" = 1 ]; then
  echo "==> Downloaded tools"
  if [ -d src-tauri/binaries ]; then
    for f in src-tauri/binaries/* src-tauri/binaries/.[!.]*; do
      [ -e "$f" ] || continue
      case "$(basename "$f")" in
        .gitkeep|*.apk) continue ;; # tracked in git, shipped as resources
      esac
      remove "$f"
    done
  fi
  echo "  note: the build needs src-tauri/binaries/imd to exist and not be empty."
  echo "        restore: bash scripts/setup.sh"
fi

if [ "$DRY" = 1 ]; then
  echo "==> Dry run: nothing was removed."
else
  echo "==> Done."
fi
